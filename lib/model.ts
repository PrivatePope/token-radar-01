// Token radar, model radar-4: an implied token value from the snapshot's own figures only.
//
//   implied = TVL^0.8 x 8 x (1 + 0.9 x clamp(7d%, -50..+150))
//                   x (0.6 + 0.7 x min(ageDays, 1460) / 1460)
//                   x (1 + 0.015 x min(chains, 10))
//
// The three signals are the protocol's own: how big it is (TVL), how fast it grew in the last
// seven days, and how long it has run with no token. A protocol that records no listing date
// takes the median age of the pre-token set. No protocol name is special-cased: the same
// function scores every row, and the same farm-plan templates describe every protocol.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  tvl_exponent: number;
  scale: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  age_floor: number;
  age_range: number;
  age_days: number;
  chain_step: number;
  chain_cap: number;
}

/** Radar-4's constants. The null-age default is not a constant: buildRadar takes the median age
 *  of the snapshot's own pre-token set, so the value follows the data, not a guess. */
export const MODEL: ModelConstants = {
  tvl_exponent: 0.8,
  scale: 8,
  growth_weight: 0.9,
  growth_floor: -50,
  growth_cap: 150,
  age_floor: 0.6,
  age_range: 0.7,
  age_days: 1460,
  chain_step: 0.015,
  chain_cap: 10,
};

